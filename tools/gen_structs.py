CTYPES = {'u8': 'u8', 'u16': 'u16', 'u32': 'u32', 'i32': 's32', 'f32': 'float', 'u64': 'TpwU64',
          'v2': 'Vec2', 'v3': 'Vec3'}
BY_SIZE = {1: 'u8', 2: 'u16', 4: 'u32', 8: 'TpwU64', 12: 'Vec3'}
SIZES = {'u8': 1, 'u16': 2, 'u32': 4, 's32': 4, 'float': 4, 'TpwU64': 8, 'Vec2': 8, 'Vec3': 12}


def schema_types(schema, out=None):
    out = {} if out is None else out
    for name, t in schema:
        if isinstance(t, tuple) and t[0] == 'inc':
            schema_types(t[1], out)
        elif isinstance(t, tuple) and t[0] == 'arr':
            if isinstance(t[2], list):
                schema_types(t[2], out)
            else:
                out[name] = t[2]
        elif isinstance(t, str):
            out[name] = t
    return out


def build(spec, src, pe):
    name, ser, schema, size, members, extra, _ = spec
    types = schema_types(schema)
    fields = []  # (offset, ctype, name, count)
    for off, t, m in members:
        fields.append((off, t, m, 1))
    for off, t, m, n in extra:
        fields.append((off, t, m, n))
    taken = {f[2] for f in fields}
    if ser:
        for f in layout(ser, src, pe, set())[1]:
            if f['off'] is None:
                continue
            fname = re.sub(r'\[.*?\]', '', f['name'])
            if fname == 'pv' or not re.match(r'\w+$', fname):
                fname = 'pv_%x' % f['off']
            if fname in taken or any(o == f['off'] for o, *_ in fields):
                if any(o == f['off'] for o, *_ in fields):
                    continue
                fname = '%s_%x' % (fname, f['off'])
            t = types.get(fname) or ('f32' if f.get('type') == 'float' else None)
            ctype = CTYPES[t] if t in CTYPES and SIZES[CTYPES[t]] == f['size'] else BY_SIZE[f['size']]
            if f.get('type') == 'float':
                ctype = 'float'
            fields.append((f['off'], ctype, fname, f.get('count', 1)))
            taken.add(fname)
    fields.sort()
    return fields


def emit(spec, fields, sizes):
    name, ser, _, size, _, _, comment = spec
    lines = ['/* %s */' % comment, 'typedef struct %s {' % name]
    pos = 0
    checks = []
    for off, ctype, fname, count in fields:
        fsize = sizes[ctype] * count
        if off < pos:
            raise ValueError('%s.%s at %#x overlaps the previous field (ends %#x)' % (name, fname, off, pos))
        if off > pos:
            lines.append('    u8 unk_%02x[0x%x];' % (pos, off - pos))
        decl = '%s %s%s;' % (ctype, fname, '[%d]' % count if count > 1 else '')
        lines.append('    %-36s /* 0x%02x */' % (decl, off))
        checks.append('TPW_CHECK(%s_%s, TPW_OFF(%s, %s) == 0x%x);' % (name, fname, name, fname, off))
        pos = off + fsize
    if size is not None:
        if pos > size:
            raise ValueError('%s: fields end at %#x past its size %#x' % (name, pos, size))
        if pos < size:
            lines.append('    u8 unk_%02x[0x%x];' % (pos, size - pos))
        checks.append('TPW_CHECK(%s_size, sizeof(%s) == 0x%x);' % (name, name, size))
        sizes[name] = size
    else:
        end = (pos + 3) & ~3
        if end > pos:
            lines.append('    u8 unk_%02x[0x%x];' % (pos, end - pos))
        lines[0] = lines[0][:-3] + '\n * Only the saved fields are known: the real object may be larger. */'
        sizes[name] = end
    lines.append('} %s;' % name)
    return '\n'.join(lines), checks


def main():
    dump, exe = sys.argv[1], sys.argv[2]
    header = sys.argv[3] if len(sys.argv) > 3 else os.path.join('re', 'types.h')
    src, pe = load_functions(dump), PE(exe)
    sizes = dict(SIZES)
    blocks, checks = [], []
    for spec in SPEC:
        text, c = emit(spec, build(spec, src, pe), sizes)
        blocks.append(text)
        checks += c
    body = '\n'.join([
        BEGIN,
        '/* Saved game objects. Offsets from the serializers\' load code, types from tools/tpsave.py. */',
        'typedef struct TpwU64 { u32 lo; u32 hi; } TpwU64;  /* 64-bit time values */',
        'typedef struct Vec2 { float x, y; } Vec2;',
        'typedef struct Vec3 { float x, y, z; } Vec3;',
        '',
        '\n\n'.join(blocks),
        '',
        '#ifndef __GHIDRA__',
        '\n'.join(checks),
        '#endif',
        END])
    text = open(header, encoding='utf-8').read()
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + body + text[text.index(END) + len(END):]
    else:
        anchor = '/* ------------------------------------------------------------------------ */\n/* Layout checks'
        text = text.replace(anchor, body + '\n\n' + anchor, 1)
    open(header, 'w', encoding='utf-8', newline='\n').write(text)
    print('%s: %d structs, %d checks' % (header, len(blocks), len(checks)))


if __name__ == '__main__':
    main()
