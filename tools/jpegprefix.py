"""Writes third_party/config/jpeg6a_prefix.h: every external name libjpeg 6a defines, renamed jpeg6a_*, so the 6a copy links next to 6b.

  python -I tools/jpegprefix.py

The names are what 6a's library sources define with GLOBAL(type) (functions) plus its exported tables. The header is force-included
(/FI) when the 6a sources compile; check.py-style verification is the link itself (a name missed here is a duplicate symbol with 6b).
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TREE = os.path.join(ROOT, 'third_party', 'jpeg-6a')
# the library's own sources (makefile.ansi's LIBOBJECTS, with jmemnobs as the memory manager)
SOURCES = '''jcapimin jcapistd jctrans jcparam jdatadst jcinit jcmaster jcmarker jcmainct jcprepct jccoefct jccolor jcsample jchuff jcphuff
jcdctmgr jfdctfst jfdctflt jfdctint jdapimin jdapistd jdtrans jdatasrc jdmaster jdinput jdmarker jdhuff jdphuff jdmainct jdcoefct jdpostct
jddctmgr jidctfst jidctflt jidctint jidctred jdsample jdcolor jquant1 jquant2 jdmerge jcomapi jutils jerror jmemmgr jmemnobs'''.split()
# tables defined without GLOBAL()
TABLES = ['jpeg_natural_order', 'jpeg_std_message_table']


def names():
    found = []
    for s in SOURCES:
        text = open(os.path.join(TREE, s + '.c'), encoding='latin-1').read()
        found += re.findall(r'^GLOBAL\s*\(.*?\)\s*\n?\s*(\w+)\s*\(', text, re.M)
    for t in TABLES:
        assert any(re.search(r'\b%s\s*\[' % t, open(os.path.join(TREE, s + '.c'), encoding='latin-1').read()) for s in SOURCES), t
    return sorted(set(found) | set(TABLES))


def main():
    out = os.path.join(ROOT, 'third_party', 'config', 'jpeg6a_prefix.h')
    lines = ['/* Generated by tools/jpegprefix.py: libjpeg 6a\'s external names, renamed so it links next to 6b. Do not edit. */', '']
    lines += ['#define %s jpeg6a_%s' % (n, n) for n in names()]
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('%s: %d names' % (os.path.relpath(out, ROOT), len(lines) - 2))


if __name__ == '__main__':
    main()
